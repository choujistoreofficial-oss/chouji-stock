-- Jalankan di Supabase SQL Editor pada project CHOUJI STOCK.
-- Tabel ini terpisah dari tabel produk/pengaturan website yang sudah ada.

create table if not exists public.nomera_orders (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  idempotency_key varchar(128) not null unique,
  service_id text not null,
  country_id text not null,
  offer_key text not null,
  expected_price numeric,
  create_attempted_at timestamptz,
  nomera_order_id text unique,
  state text not null default 'CREATE_PENDING',
  response_json jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists nomera_orders_user_created_idx
  on public.nomera_orders (user_id, created_at desc);

create table if not exists public.nomera_webhook_events (
  event_id varchar(128) primary key,
  event_name varchar(64) not null,
  payload jsonb not null,
  received_at timestamptz not null default now()
);

alter table public.nomera_orders enable row level security;
alter table public.nomera_webhook_events enable row level security;

